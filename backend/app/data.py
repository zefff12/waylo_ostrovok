def city_places(city: City) -> list[Place]:
    out = []
    for pid, name, cats, lat, lon, indoor, minutes, ticket, closed, desc in city.places:
        out.append(Place(
            id=pid, name=name, cats=cats, lat=lat, lon=lon, indoor=indoor, visit_min=minutes,
            ticket_rub=ticket, closed_weekdays=closed, description=desc,
            hours_status="unverified",
        ))
    return out


def find_city(text: str) -> City | None:
    import re

    low = text.lower()
    for c in CITIES.values():
        if any(re.search(a, low) for a in c.aliases):
            return c
    return None
